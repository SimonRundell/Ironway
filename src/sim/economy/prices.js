import { COVERAGE_TABLE, POWER_TABLES } from './priceTables.generated.js'

/**
 * Prices (DESIGN 7.4): coverage, the price multiplier (via a baked
 * lookup table for the fractional power, never a runtime `Math.pow`),
 * final price, and the cost-of-living helper DESIGN 7.7 needs. Every
 * function here uses only `+ - * /`, comparisons and `Math.floor` at
 * runtime, matching DESIGN 4.5's determinism rule for simulation maths.
 *
 * @module sim/economy/prices
 */

/** @type {number} A denominator floor so `coverage = stock / demand` never divides by exactly zero. */
const TINY_DEMAND = 1e-9

/**
 * Computes a node's stock-to-demand coverage ratio for one cargo
 * (DESIGN 7.4). A demand of zero (or anything below `TINY_DEMAND`)
 * gives `Infinity`, matching DESIGN's own comment ("demand 0 means
 * coverage = infinity") rather than an artificially huge finite number.
 *
 * @param {number} stock Current stock of this cargo at this node.
 * @param {number} demand This month's demand for this cargo at this node.
 * @returns {number} The coverage ratio (`Infinity` when demand is effectively zero).
 */
export function computeCoverage(stock, demand) {
  if (demand < TINY_DEMAND) {
    return Infinity
  }
  return stock / demand
}

/**
 * Finds the largest index `i` in an ascending array such that
 * `array[i] <= value`, by binary search (pure comparisons, no
 * transcendental functions). Used to locate `value`'s bracketing pair
 * in `COVERAGE_TABLE` without ever computing `log2(value)` at runtime.
 *
 * @param {number[]} array An ascending array with at least one element less than or equal to `value`.
 * @param {number} value The value to bracket.
 * @returns {number} The found index.
 */
function floorIndex(array, value) {
  let low = 0
  let high = array.length - 1
  while (low < high) {
    const mid = Math.floor((low + high + 1) / 2)
    if (array[mid] <= value) {
      low = mid
    } else {
      high = mid - 1
    }
  }
  return low
}

/**
 * Looks up `coverage^(-elasticity)` from the baked, log-spaced table
 * generated by `scripts/build-price-tables.mjs`: a binary search locates
 * `coverage`'s bracketing pair in `COVERAGE_TABLE`, then linearly
 * interpolates between the matching pair of `POWER_TABLES` values.
 * Never calls `Math.pow` or `Math.log`; binary search and interpolation
 * are pure arithmetic and comparisons, so this is bit-identical on
 * every JavaScript engine (DESIGN 4.5). Exported in its own right (not
 * just via `computePriceMultiplier()`) so its accuracy against a real
 * `Math.pow` reference can be tested directly, unclamped.
 *
 * @param {number} coverage A finite coverage ratio, 0 or greater (use `computePriceMultiplier()` directly for `Infinity`).
 * @param {number} elasticity A cargo's elasticity (must have a baked table — see `priceTables.generated.js`).
 * @returns {number} `coverage ** (-elasticity)`, accurate to within 0.5% over the table's range.
 * @throws {Error} If no baked table exists for `elasticity`.
 */
export function computeCoveragePower(coverage, elasticity) {
  const powers = POWER_TABLES[elasticity]
  if (!powers) {
    throw new Error(`computeCoveragePower: no baked price table for elasticity ${elasticity}. Run scripts/build-price-tables.mjs after changing cargo.json's elasticity values.`)
  }

  const lastIndex = COVERAGE_TABLE.length - 1
  if (coverage <= COVERAGE_TABLE[0]) {
    return powers[0]
  }
  if (coverage >= COVERAGE_TABLE[lastIndex]) {
    return powers[lastIndex]
  }

  const index = floorIndex(COVERAGE_TABLE, coverage)
  const lower = COVERAGE_TABLE[index]
  const upper = COVERAGE_TABLE[index + 1]
  const fraction = (coverage - lower) / (upper - lower)
  return powers[index] + (powers[index + 1] - powers[index]) * fraction
}

/**
 * Computes a cargo's price multiplier at one node (DESIGN 7.4):
 * `clamp(coverage ^ (-elasticity), pMin, pMax)`. Infinite coverage
 * (zero demand) sits exactly at `pMin` — "producers sit near pMin" and
 * PHASES.md's own "zero-demand nodes sit at the floor" — without ever
 * evaluating the table.
 *
 * @param {number} coverage From `computeCoverage()` (may be `Infinity`).
 * @param {number} elasticity The cargo's elasticity.
 * @param {{pMin: number, pMax: number}} priceRules `economy.json`'s `price` block.
 * @returns {number} The price multiplier, in `[pMin, pMax]`.
 */
export function computePriceMultiplier(coverage, elasticity, priceRules) {
  if (coverage === Infinity) {
    return priceRules.pMin
  }

  const raw = computeCoveragePower(coverage, elasticity)
  if (raw < priceRules.pMin) return priceRules.pMin
  if (raw > priceRules.pMax) return priceRules.pMax
  return raw
}

/**
 * Computes a cargo's final price at one node (DESIGN 7.4).
 *
 * @param {number} basePrice The cargo's `cargo.json` `basePrice`.
 * @param {number} priceMultiplier From `computePriceMultiplier()`.
 * @param {number} economyRevenueMultiplier The current economy level's revenue multiplier (`economy.json`'s `levels[level].revenue`).
 * @returns {number} The price.
 */
export function computePrice(basePrice, priceMultiplier, economyRevenueMultiplier) {
  return basePrice * priceMultiplier * economyRevenueMultiplier
}

/** @type {readonly string[]} The cargoes DESIGN 7.7 names for the cost-of-living basket. */
const COST_OF_LIVING_BASKET = Object.freeze(['food', 'coal', 'clothing', 'goods'])

/**
 * Computes a settlement's cost of living (DESIGN 7.7): "the price of
 * the class basket (food, coal, clothing, goods) at local prices" — the
 * sum of those four cargoes' current local prices. A basket cargo
 * missing a computed price (e.g. not yet produced/priced anywhere)
 * contributes nothing rather than breaking the sum.
 *
 * @param {Record<string, number>} localPrices This settlement's current prices, keyed by cargo id.
 * @returns {number} The cost-of-living index.
 */
export function computeCostOfLiving(localPrices) {
  return COST_OF_LIVING_BASKET.reduce((sum, cargo) => sum + (localPrices[cargo] || 0), 0)
}
